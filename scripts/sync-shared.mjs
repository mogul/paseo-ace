import { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "shared");
const pluginsDir = join(root, "plugins");

const plugins = readdirSync(pluginsDir).filter((name) => name !== "node_modules");
const clientSources = readdirSync(srcDir).filter((name) => name.endsWith(".tsx"));
const serverSources = readdirSync(srcDir).filter((name) => name.endsWith(".ts"));

const banner = "// @generated by scripts/sync-shared.mjs — edit shared/ instead of this copy.\n";

for (const plugin of plugins) {
  const clientDir = join(pluginsDir, plugin, "client");
  mkdirSync(clientDir, { recursive: true });
  for (const name of clientSources) {
    writeFileSync(join(clientDir, name), banner + readFileSync(join(srcDir, name), "utf8"), "utf8");
  }
  const serverDir = join(pluginsDir, plugin, "server");
  mkdirSync(serverDir, { recursive: true });
  for (const name of serverSources) {
    writeFileSync(join(serverDir, name), banner + readFileSync(join(srcDir, name), "utf8"), "utf8");
  }
}

console.log(`Synced ${clientSources.length} client + ${serverSources.length} server shared file(s) into ${plugins.length} plugin(s).`);
