import { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "shared");
const pluginsDir = join(root, "plugins");

const plugins = readdirSync(pluginsDir).filter((name) => name !== "node_modules");
const sources = readdirSync(srcDir).filter((name) => name.endsWith(".tsx"));

const banner = "// @generated by scripts/sync-shared.mjs — edit shared/ instead of this copy.\n";

for (const plugin of plugins) {
  const destDir = join(pluginsDir, plugin, "client");
  mkdirSync(destDir, { recursive: true });
  for (const name of sources) {
    const content = readFileSync(join(srcDir, name), "utf8");
    writeFileSync(join(destDir, name), banner + content, "utf8");
  }
}

console.log(`Synced ${sources.length} shared file(s) into ${plugins.length} plugin(s).`);
